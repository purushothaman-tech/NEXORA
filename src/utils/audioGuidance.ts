/**
 * Returns formatted narration for a given page and language, interpolating params.
 */
export function getGuidanceNarration(
  pageKey: PatientPageKey,
  language: SupportedLanguage,
  params?: Record<string, string | number>
): string {
  const langTable = AUDIO_GUIDANCE_NARRATIONS[language] || AUDIO_GUIDANCE_NARRATIONS.en;
  let text = langTable[pageKey] || AUDIO_GUIDANCE_NARRATIONS.en[pageKey] || '';

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }

  return text;
}
